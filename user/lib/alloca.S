/* alloca для i386 System V. cc не умеет выделять память на стеке вызывающего,
 * а собранный код (bash) вызывает alloca как обычную функцию. Память кладётся
 * в кадр вызывающего, под слот аргумента, который он снимет после call.
 * Эпилог вызывающего делает lea esp, [ebp-12] и этим всю её освобождает.
 *
 * На входе: [esp] — адрес возврата, [esp+4] — размер.
 * Сдвигаем esp вниз на выровненный размер, возвращаем адрес сразу за
 * аргументом. После add esp, 4 у вызывающего указатель стека стоит ровно
 * на начале блока, и следующие вызовы пишут ниже него. */
.globl alloca
alloca:
    movl 4(%esp), %eax
    testl %eax, %eax
    jz 1f
    cmpl $0x10000000, %eax          /* больше всей машины — не заворачивать счётчик */
    ja 1f
    addl $3, %eax
    andl $-4, %eax
    movl (%esp), %ecx
    subl %eax, %esp
    movl %ecx, (%esp)
    leal 8(%esp), %eax
    ret
1:
    xorl %eax, %eax
    ret
